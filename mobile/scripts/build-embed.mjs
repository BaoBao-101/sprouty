// npm run embed — the website's 3D plant (frontend/src/embed-main.tsx, the
// /embed/plant page) built with the website's own Vite config into one
// self-contained HTML page, written to src/components/plant3d-page.ts. The
// app's WebView loads it from there: nothing to download, so the plant shows
// as soon as the screen opens, offline too. Run it again after changing the
// website's 3D code; `npm run apk` and `npm run aab` run it first.
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const mobile = resolve(import.meta.dirname, '..');
const frontend = resolve(mobile, '../frontend');
const target = join(mobile, 'src/components/plant3d-page.ts');
const viteEntry = join(frontend, 'node_modules/vite/dist/node/index.js');

if (!existsSync(viteEntry)) {
  // Without the website's packages there is nothing to build with; the copy already in the app stays.
  console.warn('build-embed: frontend/node_modules is missing (npm install in frontend/); keeping the current 3D page.');
  process.exit(0);
}

const { build } = await import(pathToFileURL(viteEntry).href);
const out = mkdtempSync(join(tmpdir(), 'sprouty-embed-'));
try {
  await build({
    configFile: join(frontend, 'vite.config.ts'),
    mode: 'production',
    logLevel: 'warn',
    publicDir: false,
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    build: {
      outDir: out,
      emptyOutDir: true,
      copyPublicDir: false,
      sourcemap: false,
      cssCodeSplit: false,
      lib: { entry: join(frontend, 'src/embed-main.tsx'), formats: ['iife'], name: 'SproutyPlant3D', fileName: () => 'plant3d.js' },
    },
  });

  const files = readdirSync(out);
  const js = readFileSync(join(out, 'plant3d.js'), 'utf8');
  const css = files.filter((f) => f.endsWith('.css')).map((f) => readFileSync(join(out, f), 'utf8')).join('\n');
  const html = [
    '<!doctype html><html lang="vi"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">',
    `<style>${css.replace(/<\/style/gi, '<\\/style')}</style></head>`,
    `<body><div id="root"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`,
  ].join('');

  writeFileSync(target, [
    '// Generated by scripts/build-embed.mjs (npm run embed) from the website\'s 3D plant page,',
    '// frontend/src/embed-main.tsx. Do not edit by hand.',
    `export const PLANT_3D_HTML = ${JSON.stringify(html)};`,
    '',
  ].join('\n'));
  console.log(`build-embed: wrote src/components/plant3d-page.ts (${Math.round(html.length / 1024)} KB)`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
