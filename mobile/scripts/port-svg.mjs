/**
 * Ports the website's SVG components to react-native-svg, so the app draws
 * exactly the same icons and plant as the website (AGENTS.md: "Prefer the
 * existing SproutyIcon set"). Re-run after changing the web originals:
 *
 *   node scripts/port-svg.mjs
 *
 * It only renames the SVG elements (<path> → <Path>…) and swaps the CSS-only
 * bits for what react-native-svg understands; the drawing itself is unchanged.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const web = resolve(root, '../frontend/src/components');

const TAGS = {
  path: 'Path', circle: 'Circle', rect: 'Rect', ellipse: 'Ellipse', line: 'Line',
  polyline: 'Polyline', polygon: 'Polygon', g: 'G', defs: 'Defs', clipPath: 'ClipPath',
  linearGradient: 'LinearGradient', radialGradient: 'RadialGradient', stop: 'Stop',
  text: 'SvgText', mask: 'Mask', svg: 'Svg',
};

function renameTags(source) {
  let out = source;
  for (const [from, to] of Object.entries(TAGS)) {
    const open = new RegExp('<' + from + String.raw`(?=[\s>/])`, 'g');
    out = out.replace(open, `<${to}`).replaceAll(`</${from}>`, `</${to}>`);
  }
  return out;
}

function header(name) {
  return `// Generated by scripts/port-svg.mjs from frontend/src/components/${name}. Do not edit by hand.\n`;
}

// ── SproutyIcon ────────────────────────────────────────────────────────────
{
  const src = readFileSync(resolve(web, 'icons/SproutyIcon.tsx'), 'utf8');
  const start = src.indexOf('export type IconName');
  const pathsStart = src.indexOf('const PATHS');
  const pathsEnd = src.indexOf('export function SproutyIcon');
  const types = src.slice(start, src.indexOf('interface Props'));
  const helpers = src.slice(src.indexOf('/** Shared geometry'), pathsStart)
    // The fill is the outline's colour, faded — what the website shows where no
    // --icon-accent is set. react-native-svg resolves currentColor from `color`.
    .replace("const ACCENT = 'var(--icon-accent, currentColor)';", "const ACCENT = 'currentColor';");
  const paths = renameTags(src.slice(pathsStart, pathsEnd)).replace('React.ReactNode', 'ReactNode');
  const out = `${header('icons/SproutyIcon.tsx')}import type { ReactElement, ReactNode } from 'react';
import Svg, { Circle, Ellipse, Path, Rect } from 'react-native-svg';

${types}
${helpers}
${paths}
/** One of Sprouty's icons, in the colour of \`color\` (outline) with a soft fill of the same. */
export function Icon({ name, size = 24, color = '#34513A' }: { name: IconName; size?: number; color?: string }) {
  const node = (PATHS as Record<string, ReactElement>)[name] ?? PATHS.leaf;
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24" color={color}>
      {node}
    </Svg>
  );
}
`;
  writeFileSync(resolve(root, 'src/components/Icon.tsx'), out);
  console.log('src/components/Icon.tsx');
}

// ── PlantForms (the species' bodies) ──────────────────────────────────────
{
  let src = readFileSync(resolve(web, 'PlantForms.tsx'), 'utf8');
  src = renameTags(src)
    // Web-only attributes have no meaning on a phone.
    .replace(/\s(className|role|aria-[a-z]+)=\{[^}]*\}/g, '')
    .replace(/\s(className|role|aria-[a-z]+)="[^"]*"/g, '');
  const used = [...new Set([...src.matchAll(/<(Path|Circle|Rect|Ellipse|Line|Polyline|Polygon|G|Defs|ClipPath|LinearGradient|RadialGradient|Stop|SvgText|Mask)\b/g)].map((m) => m[1]))].sort();
  writeFileSync(resolve(root, 'src/components/PlantForms.tsx'),
    `${header('PlantForms.tsx')}import { ${used.join(', ')} } from 'react-native-svg';\n${src}`);
  console.log('src/components/PlantForms.tsx');
}

// ── PlantArt (the scene and the pot) ──────────────────────────────────────
{
  let src = readFileSync(resolve(web, 'PlantArt.tsx'), 'utf8');
  src = renameTags(src)
    .replace("import { PlantBody, type FruitShape, type PlantForm } from '@/components/PlantForms';", "import { PlantBody, type FruitShape, type PlantForm } from './PlantForms';")
    .replace("import type { PotKey } from './garden-looks';", "export type PotKey = 'plain' | 'terracotta' | 'ceramic' | 'porcelain';")
    // SVG ids must be plain ASCII for react-native-svg's url(#…) references.
    .replace("useId().replace(/:/g, '')", "useId().replace(/[^a-zA-Z0-9_-]/g, '')")
    // Template literals first: their ${…} would end a {…} match early.
    .replace(/\s(className|role|aria-label)=\{`[^`]*`\}/g, '')
    .replace(/\s(className|role|aria-label)=\{[^}]*\}/g, '')
    .replace(/\s(className|role|aria-label)="[^"]*"/g, '')
    .replace(/\s+className\?: string;/, '')
    .replace(/\s+className,\n/, '\n')
    .replace('fontFamily="inherit"', 'fontFamily="BeVietnamPro_700Bold"');
  const used = [...new Set([...src.matchAll(/<(Path|Circle|Rect|Ellipse|Line|Polyline|Polygon|G|Defs|ClipPath|LinearGradient|RadialGradient|Stop|SvgText|Mask)\b/g)].map((m) => m[1]))].sort();
  src = src.replace("import { useId } from 'react';", `import { useId } from 'react';\nimport Svg, { ${used.map((t) => (t === 'SvgText' ? 'Text as SvgText' : t)).join(', ')} } from 'react-native-svg';`);
  writeFileSync(resolve(root, 'src/components/PlantArt.tsx'), `${header('PlantArt.tsx')}${src}`);
  console.log('src/components/PlantArt.tsx');
}
