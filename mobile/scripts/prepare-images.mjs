/**
 * Ships the website's product photos and Sprouty illustrations inside the app,
 * scaled for a phone.
 *
 * The API names seeded product photos by their website path
 * ("/assets/images/products/bean/bean-standard.png"). Those files are print-
 * sized PNGs of 2–4 MB; downloading one per shop card would cost a parent's
 * mobile data and make the shop crawl. So the ones the app shows are copied
 * into assets/web/ at phone size, and src/lib/bundled-images.ts maps each
 * website path to its bundled copy (React Native can only bundle files it
 * sees in a literal require()). Paths not in the map load from the website.
 *
 *   npm run images
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative, resolve } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const from = resolve(root, '../frontend/public');
const to = resolve(root, 'assets/web');

/**
 * Folders under assets/images to bundle, with the longest side each may have.
 * `photo` folders are photographs saved as PNG on the website (several MB
 * each); they ship as JPEG, still under their website name in the map.
 */
const FOLDERS = [
  ['assets/images/products', 900],
  ['assets/images/sprouty-icons', 360],
  ['assets/images/workshop/register', 800, 'photo'],
];
/** Single pictures outside those folders: the Sprouty AI mark. */
const FILES = [
  ['assets/images/sprouty-mark.png', 160],
];
const IMAGE = new Set(['.png', '.jpg', '.jpeg', '.webp']);

async function* files(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(path);
    else yield path;
  }
}

const entries = [];
async function bundle(src, max, kind) {
  const ext = extname(src).toLowerCase();
  if (!IMAGE.has(ext)) return;
  const rel = relative(from, src).split('\\').join('/');
  const asPng = ext === '.png' && kind !== 'photo';
  // assets/web/products/bean/bean-standard.png
  let dest = join(to, rel.replace(/^assets\/images\//, ''));
  if (ext === '.png' && !asPng) dest = dest.replace(/\.png$/i, '.jpg');
  await mkdir(dirname(dest), { recursive: true });
  let pipeline = sharp(src).rotate().resize({ width: max, height: max, fit: 'inside', withoutEnlargement: true });
  pipeline = asPng ? pipeline.png({ palette: true, quality: 88, effort: 8 }) : pipeline.flatten({ background: '#ffffff' }).jpeg({ quality: 78, mozjpeg: true });
  await pipeline.toFile(dest);
  entries.push([`/${rel}`, relative(resolve(root, 'src/lib'), dest).split('\\').join('/')]);
}
for (const [folder, max, kind] of FOLDERS) {
  for await (const src of files(join(from, folder))) await bundle(src, max, kind);
}
for (const [file, max] of FILES) await bundle(join(from, file), max);

entries.sort(([a], [b]) => a.localeCompare(b));
const body = entries.map(([web, local]) => `  '${web}': require('${local}'),`).join('\n');
await writeFile(resolve(root, 'src/lib/bundled-images.ts'), `// Generated by scripts/prepare-images.mjs. Do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports */

/** Website image paths that ship inside the app, at phone size. */
export const BUNDLED_IMAGES: Record<string, number> = {
${body}
};
`);
console.log(`${entries.length} images bundled into assets/web/`);
